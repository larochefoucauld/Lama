// Lama bytecode opcodes

#pragma once

#include <cstdint>

namespace lama {

enum class Op : std::uint8_t {
  Add = 0x01, Sub = 0x02, Mul = 0x03, Div = 0x04, Mod = 0x05,
  Lt = 0x06, Le = 0x07, Gt = 0x08, Ge = 0x09, Eq = 0x0A, Ne = 0x0B,
  And = 0x0C, Or = 0x0D,
  Const = 0x10, String = 0x11, Sexp = 0x12, Sta = 0x14, Jmp = 0x15,
  End = 0x16, Drop = 0x18, Dup = 0x19, Swap = 0x1A, Elem = 0x1B,
  LdGlo = 0x20, LdLoc = 0x21, LdArg = 0x22, LdClo = 0x23,
  StGlo = 0x40, StLoc = 0x41, StArg = 0x42, StClo = 0x43,
  CjmpZ = 0x50, CjmpNz = 0x51, Begin = 0x52, BeginClosure = 0x53,
  Closure = 0x54, Callc = 0x55, Call = 0x56, Tag = 0x57, Array = 0x58,
  Fail = 0x59, FailKeep = 0x5A, Line = 0x5B,
  PattStrCmp = 0x60, PattString = 0x61, PattArray = 0x62, PattSexp = 0x63,
  PattBoxed = 0x64, PattUnboxed = 0x65, PattClosure = 0x66,
  Barray = 0x74,
  Eof = 0xFF,
};

const char *op_name(std::uint8_t opcode);

}  // namespace lama
